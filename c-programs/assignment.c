//wap to perform arithmetic operations on two numbers
#include<stdio.h>
int main()
{
    int a=19,b=5;
    printf("Sum =%d\n",a+b);
    printf("Difference =%d\n",a-b);
    printf("Multiplication =%d\n",a*b);
    printf("Division(quotient) =%d\n",a/b);
    printf("Modulus(Remainder) =%d\n",a%b);
    return 0;
}
 